CREATE OR REPLACE TRIGGER emp_after_insert
AFTER INSERT ON EMP FOR EACH ROW
BEGIN INSERT INTO NEWEMP(EID,ENAME,DEPTNO,DEPTNAME,GENDER,AGE,BASICSAL)
 VALUES(:NEW.EID,:NEW.ENAME,:NEW.DEPTNO,:NEW.DEPTNAME,:NEW.GENDER,:NEW.AGE,:NEW.BASICSAL); END; /
