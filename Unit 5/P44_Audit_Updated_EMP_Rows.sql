CREATE OR REPLACE TRIGGER emp_after_update
AFTER UPDATE ON EMP FOR EACH ROW
BEGIN INSERT INTO NEWEMP(EID,ENAME,DEPTNO,DEPTNAME,GENDER,AGE,BASICSAL)
 VALUES(:OLD.EID,:OLD.ENAME,:OLD.DEPTNO,:OLD.DEPTNAME,:OLD.GENDER,:OLD.AGE,:OLD.BASICSAL); END; /
